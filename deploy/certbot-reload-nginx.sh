#!/usr/bin/env bash
# Перезагрузка nginx после продления сертификата.
#
# Нужен для сертификата ЕСА (вход.вмалмыже.рф): он выпущен плагином webroot
# (проверка ACME идёт через edge → бокс → location /.well-known/acme-challenge/),
# а webroot, в отличие от плагина nginx, НЕ перезагружает nginx сам — после
# продления сервис продолжал бы отдавать старый сертификат до его истечения.
#
# Полезно и остальным сертификатам бокса: перезагрузка nginx безопасна и
# занимает секунду.
set -euo pipefail
systemctl reload nginx
