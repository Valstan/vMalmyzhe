// JSON внутри <script> — не то же самое, что JSON в теле ответа: браузер режет
// поток по литералу `</script`, где бы тот ни встретился, даже внутри строки
// JSON. Строка `</script><script>...` в заголовке новости из ВК закрыла бы наш
// тег и открыла чужой (G209).
//
// Экранируем каждый `<` шестнадцатеричным escape — это валидный JSON, парсер
// вернёт исходный символ, а разборщик HTML литерала уже не увидит. Единственная
// точка, через которую JSON-LD попадает в разметку: два места с одинаковым
// `.replace()` расходятся молча, одно — нет.
export function jsonLdHtml(data: unknown): string {
  return JSON.stringify(data).replace(/</g, '\\u003c')
}
