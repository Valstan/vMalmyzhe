// Номер счётчика Яндекс.Метрики. Нужен и JS-счётчику, и картиночному информеру
// в подвале; нет номера — не рендерится ни то, ни другое, сайт полностью
// рабочий.
//
//   NEXT_PUBLIC_YANDEX_METRIKA_ID — номер счётчика
//
// Здесь был ещё серверный запрос в Reporting API за парой «сегодня / вчера»:
// штатный информер Яндекса отдаёт только сегодняшние числа, а хотелось видеть
// динамику. Убрано 10.08 решением владельца: цифры за вчера/неделю требуют
// отдельного OAuth-токена, который надо выпускать и потом продлевать, и эта
// возня не окупается ради строки в подвале. Если решение переиграют — код
// лежит в истории (`git log -- web/src/lib/metrika.ts`), восстанавливать
// заново не нужно.

// Номер счётчика подставляется внутрь инлайнового `<script>` (YandexMetrika.tsx)
// — та же поверхность, что JSON-LD в G209, только источник не пользовательский,
// а прод-env. Пропускаем одни цифры: класс закрыт по конструкции, а заодно
// опечатка в переменной окружения не даёт молча битый счётчик — информер и
// счётчик просто не рендерятся, как и при пустом значении.
export function normalizeMetrikaId(raw: string | undefined): string {
  const value = (raw || '').trim()
  return /^\d+$/.test(value) ? value : ''
}

export const METRIKA_ID = normalizeMetrikaId(process.env.NEXT_PUBLIC_YANDEX_METRIKA_ID)
